import fs from "node:fs/promises";
import path from "node:path";

export const DEFAULT_OUT_FILE = "generated/collections.d.ts";
export const DEFAULT_TYPES_MODULE = "@tuqulore-inc/eleventy-preset/eleventy";

const HEADER = "// Generated by @tuqulore-inc/eleventy-collections. Do not edit.\n";

/**
 * Build the declaration-merging `.d.ts` for the given collections. Types are
 * not computed here: each entry points at its schema module, and TypeScript
 * derives the entry type from the module's `schema` and `type` exports.
 *
 * @param {import("./discover.js").CollectionSource[]} collections
 * @param {Object} options
 * @param {string} options.outFile
 * @param {string} options.typesModule
 * @returns {string}
 */
export function renderTypes(collections, { outFile, typesModule }) {
  if (collections.length === 0) return `${HEADER}export {};\n`;

  const outDir = path.dirname(path.resolve(outFile));
  const entries = collections.map(({ name, schemaPath }) => {
    let specifier = path.relative(outDir, schemaPath).split(path.sep).join("/");
    if (!specifier.startsWith(".")) specifier = `./${specifier}`;
    return `    ${JSON.stringify(name)}: CollectionOf<typeof import(${JSON.stringify(specifier)})>;`;
  });

  // NOTE: Only `typesModule` is imported. Projects using the preset do not
  // depend on this package directly, so it may not be resolvable from here.
  return `${HEADER}import type { EleventyCollectionItem } from ${JSON.stringify(typesModule)};

type Output<M> = M extends { schema: { "~standard": { types?: { output: infer O } } } } ? O : never;

type CollectionOf<M> = M extends { type: "data" }
  ? Array<{ id: string; inputPath: string; data: Output<M> }>
  : Array<EleventyCollectionItem<Output<M>>>;

declare module ${JSON.stringify(typesModule)} {
  interface EleventyCollections {
${entries.join("\n")}
  }
}
`;
}

/**
 * Write the generated types, only when their content changes. Nothing is
 * written while there are no collections and no file yet.
 *
 * @param {import("./discover.js").CollectionSource[]} collections
 * @param {Object} [options]
 * @param {string} [options.outFile]
 * @param {string} [options.typesModule]
 * @returns {Promise<boolean>} Whether the file was written
 */
export async function generateTypes(
  collections,
  { outFile = DEFAULT_OUT_FILE, typesModule = DEFAULT_TYPES_MODULE } = {},
) {
  const current = await fs.readFile(outFile, "utf8").catch((error) => {
    if (error.code === "ENOENT") return undefined;
    throw error;
  });
  // NOTE: With no collections, an existing file is still rewritten (to an empty
  // module) so that it does not keep importing a deleted schema.
  if (current === undefined && collections.length === 0) return false;

  const content = renderTypes(collections, { outFile, typesModule });
  if (content === current) return false;

  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, content);
  return true;
}
